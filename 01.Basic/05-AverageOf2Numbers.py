# Code 5: This code will take 2 numbers from the user and calculate the average of those 2 numbers.
# Store input numbers
num1= input("Enter first number: ")
num2= input("Enter second number: ")
# Calculate average
average = (float(num1) + float(num2)) / 2
# Display the average
print("The average of", num1, "and", num2, "is:", average)
