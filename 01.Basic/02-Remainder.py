# Code 2: Finding the remainder
# This program finds the remainder when one number is divided by another
# Store input numbers
num1 = input("Enter first number: ")
num2 = input("Enter second number: ")
# Find the remainder
remainder = float(num1) % float(num2)
# Display the remainder
# print("The remainder of {0} divided by {1} is {2}".format(num1, num2, remainder))
# print(f"The remainder of {num1} divided by {num2} is {remainder}")
print("The remainder of", num1, "divided by", num2, "is", remainder)