# Code 3 - Type
# Type is a built-in function that returns the type of an object.
# User will enter a value and the program will print the type of that value.
value = input("Enter a value: ")
print("The type of", value, "is", type(value))
# Always remember that input() function returns a string, so the type will always be <class 'str'> unless you convert it to another type.